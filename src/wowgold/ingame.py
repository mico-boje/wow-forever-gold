"""Send farming routes to the game.

Routes you send from the Farms page are kept in `data/routes.json` and written as `Routes.lua`
into the installed WowGoldLogger addon folder. WoW reads addon files at login or /reload, and
the addon then registers each route as an RXPGuides guide (a `.loop` step: the route drawn on
the map, with RXP's arrow).
"""

from __future__ import annotations

import json
import os
from datetime import UTC, datetime
from glob import glob
from pathlib import Path

MAX_ROUTES = 20
ROUTES_FILE = "Routes.lua"
ADDON_GLOBS = (
    "/mnt/c/Program Files (x86)/World of Warcraft/*/Interface/AddOns/WowGoldLogger",
    "/mnt/c/Program Files/World of Warcraft/*/Interface/AddOns/WowGoldLogger",
    "/mnt/*/World of Warcraft/*/Interface/AddOns/WowGoldLogger",
    "/mnt/*/Games/World of Warcraft/*/Interface/AddOns/WowGoldLogger",
    os.path.expanduser(
        "~/Games/*/drive_c/Program Files*/World of Warcraft/*/Interface/AddOns/WowGoldLogger"
    ),
)


def _store(data_dir: Path) -> Path:
    return data_dir / "routes.json"


def load_routes(data_dir: Path) -> list[dict]:
    try:
        routes = json.loads(_store(data_dir).read_text())
    except (OSError, json.JSONDecodeError):
        return []
    return [r for r in routes if isinstance(r, dict) and r.get("id")]


def _valid(route: dict) -> bool:
    pts = route.get("points")
    mobs = route.get("mobs", [])
    return (
        isinstance(mobs, list)
        and len(mobs) <= 12
        and all(isinstance(m, str) and len(m) <= 80 for m in mobs)
        and route.get("kind") in ("world", "map")
        and isinstance(route.get("map"), int)
        and isinstance(pts, list)
        and 1 <= len(pts) <= 200
        and all(
            isinstance(p, list) and len(p) == 2 and all(isinstance(v, int | float) for v in p)
            for p in pts
        )
    )


def add_route(
    data_dir: Path,
    rid: str,
    name: str,
    zone: str,
    note: str,
    route: dict,
    item: int | None = None,
) -> list[dict]:
    """Keep a route (replacing one with the same id); newest first, at most MAX_ROUTES.
    `item`: the farm's main item, which keeps the route's guide step open in RXPGuides."""
    if not _valid(route):
        raise ValueError("not a valid route")
    entry = {
        "id": str(rid)[:120],
        "item": int(item) if item else None,
        "name": str(name)[:120],
        "zone": str(zone)[:80],
        "note": str(note)[:300],
        "sent_at": datetime.now(UTC).isoformat(timespec="seconds"),
        **route,
    }
    routes = [entry] + [r for r in load_routes(data_dir) if r["id"] != entry["id"]]
    routes = routes[:MAX_ROUTES]
    _store(data_dir).parent.mkdir(parents=True, exist_ok=True)
    _store(data_dir).write_text(json.dumps(routes, indent=1))
    return routes


def remove_route(data_dir: Path, rid: str) -> list[dict]:
    routes = [r for r in load_routes(data_dir) if r["id"] != rid]
    _store(data_dir).write_text(json.dumps(routes, indent=1))
    return routes


def _lua_str(s: str) -> str:
    out = str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").replace("\r", " ")
    return f'"{out}"'


def routes_lua(routes: list[dict]) -> str:
    lines = [
        "-- Generated by wowgold (Farms page > Send to game). Overwritten on every send.",
        "WowGoldLoggerRoutes = {",
    ]
    for r in routes:
        flat = ",".join(f"{v:g}" for p in r["points"] for v in p)
        lines.append(
            "  { "
            + ", ".join(
                [
                    f"id = {_lua_str(r['id'])}",
                    f"name = {_lua_str(r['name'])}",
                    f"zone = {_lua_str(r.get('zone', ''))}",
                    f"note = {_lua_str(r.get('note', ''))}",
                    f"kind = {_lua_str(r['kind'])}",
                    f"map = {int(r['map'])}",
                    f"range = {int(r.get('range') or 25)}",
                    f"item = {int(r['item'])}" if r.get("item") else "item = nil",
                    "mobs = { " + ", ".join(_lua_str(m) for m in r.get("mobs") or []) + " }",
                    f"points = {{ {flat} }}",
                ]
            )
            + " },"
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def addon_dirs(configured: Path | None = None) -> list[Path]:
    if configured:
        return [configured] if configured.is_dir() else []
    return sorted({Path(p) for pattern in ADDON_GLOBS for p in glob(pattern)})


def write_routes(data_dir: Path, configured: Path | None = None) -> list[Path]:
    """Write Routes.lua into every installed WowGoldLogger folder. Returns where."""
    text = routes_lua(load_routes(data_dir))
    written = []
    for d in addon_dirs(configured):
        (d / ROUTES_FILE).write_text(text, encoding="utf-8")
        written.append(d / ROUTES_FILE)
    return written
